# Helper function to resolve map path from various input formats
function resolve_map_path(input::String)
    # If input already has .jld2 extension, treat as path
    if endswith(input, ".jld2")
        # Check if it exists as-is (absolute or relative to cwd)
        if isfile(input)
            return input
        else
            error("Map file not found: $input")
        end
    else
        # No extension - assume it's a map name in the maps/ folder (backwards compatibility)
        map_path = joinpath("maps", "$input.jld2")
        if !isfile(map_path)
            error("Map file not found: $map_path")
        end
        return map_path
    end
end

# Modified loadmap function to accept file paths and load multi-ship GameMap
function loadmap(map_input::Union{Nothing,String})
    if isnothing(map_input)
        @info "No map loaded..."
        return GameMap()
    else
        map_path = resolve_map_path(map_input)
        # Open the JLD2 file and look for known top-level keys: `ships` or `stored_gamemap`
        jldopen(map_path, "r") do f
            if haskey(f, "ships")
                ships = read(f, "ships")
                @info "Map loaded successfully from: $map_path (ships)"
                return GameMap(ships = ships)
            elseif haskey(f, "stored_gamemap")
                gm = read(f, "stored_gamemap")
                try
                    if hasproperty(gm, :ships)
                        @info "Map loaded successfully from: $map_path (stored_gamemap)"
                        return gm
                    end
                catch
                end

                if isa(gm, Array)
                    d = Dict{Symbol, ShipMap}()
                    for p in gm
                        d[p.first] = p.second
                    end
                    @info "Map loaded successfully from: $map_path (stored_gamemap as array)"
                    return GameMap(ships = d)
                end

                if isa(gm, Dict) && haskey(gm, :ships)
                    @info "Map loaded successfully from: $map_path (stored_gamemap as dict)"
                    return GameMap(ships = gm[:ships])
                end

                error("Could not interpret stored_gamemap structure in: $map_path")
            else
                error("Map file does not contain 'ships' or 'stored_gamemap': $map_path")
            end
        end
    end
end


"""
    compare_component_types(comp1::ComponentBehavior, comp2::ComponentBehavior)

Compare if two components are of the same type (allowing for some flexibility in parameters).
"""
function compare_component_types(comp1::ComponentBehavior, comp2::ComponentBehavior)
    return typeof(comp1) == typeof(comp2)
end

"""
    compare_pipe_behaviors(pipe1::PipeBehavior, pipe2::PipeBehavior; tolerance=1e-6)

Compare two pipe behaviors including type and tunable parameters.
"""
function compare_pipe_behaviors(pipe1::PipeBehavior, pipe2::PipeBehavior; tolerance=1e-6)
    # Check type match
    if typeof(pipe1) != typeof(pipe2)
        return false, "Type mismatch: $(typeof(pipe1)) vs $(typeof(pipe2))"
    end
    
    # Check tunables
    try
        tunables1 = get_pipe_tunables(pipe1)
        tunables2 = get_pipe_tunables(pipe2)
        
        if length(tunables1) != length(tunables2)
            return false, "Different number of tunables: $(length(tunables1)) vs $(length(tunables2))"
        end
        
        for (i, (t1, t2)) in enumerate(zip(tunables1, tunables2))
            if abs(t1.current_val - t2.current_val) > tolerance
                return false, "Tunable $i differs: $(t1.current_val) vs $(t2.current_val)"
            end
        end
        
        return true, "Pipe behaviors match"
    catch e
        return false, "Error comparing pipe behaviors: $e"
    end
end

"""
    elements_approximately_equal(elem1::AbsoluteElement, elem2::AbsoluteElement; tolerance=1e-9)

Compare two AbsoluteElements for approximate equality.
Uses exact equality for type and connections, approximate equality for values.
"""
function elements_approximately_equal(elem1::AbsoluteElement, elem2::AbsoluteElement; tolerance=1e-9)
    # Type must match exactly
    if elem1.type != elem2.type
        return false
    end
    
    # Connections must match exactly
    if elem1.connections != elem2.connections
        return false
    end
    
    # Dependent id must match exactly
    if elem1.dependent_id != elem2.dependent_id
        return false
    end
    
    # Value comparison with tolerance for floating point errors
    return isapprox(elem1.value, elem2.value; rtol=tolerance, atol=tolerance)
end

"""
    find_matching_element(elem::AbsoluteElement, elements::Vector{AbsoluteElement}; tolerance=1e-9)

Find an element in a list that approximately matches the given element.
Returns the index of the matching element, or nothing if no match found.
"""
function find_matching_element(elem::AbsoluteElement, elements::Vector{AbsoluteElement}; tolerance=1e-9)
    for (i, candidate) in enumerate(elements)
        if elements_approximately_equal(elem, candidate; tolerance=tolerance)
            return i
        end
    end
    return nothing
end

"""
    compare_elements(original_map::GameMap, generated_map::GameMap; tolerance=1e-9)

Compare the circuit elements produced by two maps by examining their AbsoluteElements.
This catches circuit topology errors that structural comparison might miss.

Uses approximate equality for element values to handle floating point precision issues.
"""
function compare_elements(original_map::GameMap, generated_map::GameMap; tolerance=1e-9)
    # Get all active elements from both maps
    orig_elements = list_elements(original_map)
    gen_elements = list_elements(generated_map)
    
    # Create working copies we can modify
    remaining_gen_elements = copy(gen_elements)
    
    # Track unmatched elements
    missing_elements = []
    extra_elements = []
    
    # Try to match each original element with a generated element
    for orig_elem in orig_elements
        match_idx = find_matching_element(orig_elem, remaining_gen_elements; tolerance=tolerance)
        if isnothing(match_idx)
            # No match found - this element is missing in generated
            push!(missing_elements, (orig_elem, 1))
        else
            # Match found - remove from remaining elements
            deleteat!(remaining_gen_elements, match_idx)
        end
    end
    
    # Any remaining generated elements are extras
    for gen_elem in remaining_gen_elements
        push!(extra_elements, (gen_elem, 1))
    end
    
    # Check if element sets match
    elements_match = isempty(missing_elements) && isempty(extra_elements)
    
    return (
        elements_match = elements_match,
        original_element_count = length(orig_elements),
        generated_element_count = length(gen_elements),
        missing_elements = missing_elements,
        extra_elements = extra_elements
    )
end

"""
    is_safe_to_share(T::Type)

Determine if a type is safe to share between multiple map locations.

Conservative approach: Only `isbitstype` types are considered safe to share.
These are "plain data" types with no references - primitives and immutable structs
containing only other isbits types. They have no identity and cannot be mutated.

Examples of safe types: Int, Float64, ScrapPipeBehav (struct with Float64 field)
Examples of unsafe types: Any component with state, vectors, mutable structs

This may produce false positives (flagging safe immutable types), but that's
acceptable - Julia is unlikely to optimize sharing for non-isbits types anyway,
and the comparison against the source map serves as a validation fallback.
"""
function is_safe_to_share(T::Type)
    return isbitstype(T)
end

"""
    check_component_identity(map::GameMap)

Check for shared component references (same object used in multiple tiles).
This catches a critical bug where stateful components are reused, causing
state changes to affect all instances.

Returns (is_valid, error_messages) where is_valid is false if shared references detected.

Note: Only checks components/pipes that are NOT safe to share. Immutable, stateless
types (like simple pipe structs) are excluded to avoid false positives.
"""
function check_component_identity(map::GameMap)
    messages = String[]
    
    # Build map from component object_id to list of (ship, tile) using it
    component_locations = Dict{UInt, Vector{Tuple{Symbol, TileCoord}}}()

    for (ship_name, ship) in map.ships
        for (coord, cot) in ship.components
            # Skip types that are safe to share
            comp_type = typeof(cot.component)
            if is_safe_to_share(comp_type)
                continue
            end

            obj_id = objectid(cot.component)
            if !haskey(component_locations, obj_id)
                component_locations[obj_id] = Tuple{Symbol, TileCoord}[]
            end
            push!(component_locations[obj_id], (ship_name, coord))
        end
    end

    # Find any components used at multiple locations
    shared_components = filter(p -> length(p.second) > 1, component_locations)

    if !isempty(shared_components)
        for (obj_id, locs) in shared_components
            (s0, c0) = locs[1]
            comp = map.ships[s0].components[c0].component
            comp_type = typeof(comp)
            coord_str = join([string("(:", s, ", TileCoord(", c.q, ", ", c.r, "))") for (s,c) in locs], ", ")
            push!(messages, "  ⚠️  $(comp_type) shared between components: $coord_str")
        end
    end

    # Check for shared pipe behaviors (only for types that aren't safe to share)
    pipe_locations = Dict{UInt, Vector{Tuple{Symbol, EdgeCoord}}}()
    for (ship_name, ship) in map.ships
        for (edge, pipe) in ship.pipe_behaviors
        # Skip types that are safe to share
        pipe_type = typeof(pipe)
        if is_safe_to_share(pipe_type)
            continue
        end
        
        obj_id = objectid(pipe)
        if !haskey(pipe_locations, obj_id)
            pipe_locations[obj_id] = EdgeCoord[]
        end
        push!(pipe_locations[obj_id], edge)
    end
    
    shared_pipes = filter(p -> length(p.second) > 1, pipe_locations)
    
    if !isempty(shared_pipes)
        for (obj_id, edges) in shared_pipes
            pipe = map.pipe_behaviors[edges[1]]
            pipe_type = typeof(pipe)
            edge_str = join(["EdgeCoord(...)" for _ in edges], ", ")
            push!(messages, "  ⚠️  $(pipe_type) shared between $(length(edges)) edges")
        end
    end
    
    is_valid = isempty(shared_components) && isempty(shared_pipes)
    
    return (is_valid, join(messages, "\n"))
end

"""
    compare_component_tunables(comp1::ComponentBehavior, comp2::ComponentBehavior; tolerance=1e-6)

Compare tunable parameters of two components within a tolerance.
"""
function compare_component_tunables(comp1::ComponentBehavior, comp2::ComponentBehavior; tolerance=1e-6)
    try
        tunables1 = get_tunables(comp1)
        tunables2 = get_tunables(comp2)
        
        if length(tunables1) != length(tunables2)
            return false, "Different number of tunables: $(length(tunables1)) vs $(length(tunables2))"
        end
        
        for (i, (t1, t2)) in enumerate(zip(tunables1, tunables2))
            if abs(t1.current_val - t2.current_val) > tolerance
                return false, "Tunable $i differs: $(t1.current_val) vs $(t2.current_val)"
            end
        end
        
        return true, "Tunables match"
    catch e
        return false, "Error comparing tunables: $e"
    end
end

"""
    compare_maps(original_map::GameMap, generated_map::GameMap; tolerance=1e-6)

Compare two GameMaps and return detailed comparison results.
"""
function compare_maps(original_map::GameMap, generated_map::GameMap; tolerance=1e-6)
    results = Dict{String, Any}()

    # Ship name comparison
    orig_ship_names = collect(keys(original_map.ships))
    gen_ship_names = collect(keys(generated_map.ships))
    results["ship_names_match"] = Set(orig_ship_names) == Set(gen_ship_names)
    results["original_ships"] = orig_ship_names
    results["generated_ships"] = gen_ship_names

    # Flatten components and pipes across ships, keyed by (ship, coord)
    function flatten_components(map::GameMap)
        comps = Dict{Tuple{Symbol, TileCoord}, ComponentOnTile}()
        for (s, ship) in map.ships
            for (coord, comp) in ship.components
                comps[(s, coord)] = comp
            end
        end
        return comps
    end

    function flatten_pipes(map::GameMap)
        pipes = Dict{Tuple{Symbol, EdgeCoord}, PipeBehavior}()
        for (s, ship) in map.ships
            for (edge, pipe) in ship.pipe_behaviors
                pipes[(s, edge)] = pipe
            end
        end
        return pipes
    end

    function flatten_surfaces(map::GameMap)
        tiles = Set{Tuple{Symbol, TileCoord}}()
        for (s, ship) in map.ships
            for coord in ship.ship_tiles
                push!(tiles, (s, coord))
            end
        end
        return tiles
    end

    orig_comps = flatten_components(original_map)
    gen_comps = flatten_components(generated_map)
    orig_component_count = length(orig_comps)
    gen_component_count = length(gen_comps)
    results["component_count_match"] = orig_component_count == gen_component_count
    results["original_component_count"] = orig_component_count
    results["generated_component_count"] = gen_component_count

    orig_pipes = flatten_pipes(original_map)
    gen_pipes = flatten_pipes(generated_map)
    orig_pipe_count = length(orig_pipes)
    gen_pipe_count = length(gen_pipes)
    results["pipe_count_match"] = orig_pipe_count == gen_pipe_count
    results["original_pipe_count"] = orig_pipe_count
    results["generated_pipe_count"] = gen_pipe_count

    # Compare components by (ship, coord)
    tile_mismatches = []
    missing_in_generated = []
    extra_in_generated = []

    for ((s, coord), orig_comp) in orig_comps
        key = (s, coord)
        if haskey(gen_comps, key)
            gen_comp = gen_comps[key]
            # Compare component types
            if !compare_component_types(orig_comp.component, gen_comp.component)
                push!(tile_mismatches, (s, coord, "Type mismatch", typeof(orig_comp.component), typeof(gen_comp.component)))
            end
            # Compare rotations
            if orig_comp.rotation != gen_comp.rotation
                push!(tile_mismatches, (s, coord, "Rotation mismatch", orig_comp.rotation, gen_comp.rotation))
            end
            # Compare tunables
            tunable_match, tunable_msg = compare_component_tunables(orig_comp.component, gen_comp.component; tolerance=tolerance)
            if !tunable_match
                push!(tile_mismatches, (s, coord, "Tunable mismatch", tunable_msg, ""))
            end
        else
            push!(missing_in_generated, (s, coord))
        end
    end

    for ((s, coord), _) in gen_comps
        if !haskey(orig_comps, (s, coord))
            push!(extra_in_generated, (s, coord))
        end
    end

    results["tile_mismatches"] = tile_mismatches
    results["missing_tiles"] = missing_in_generated
    results["extra_tiles"] = extra_in_generated

    # Compare pipe behaviors
    pipe_mismatches = []
    missing_pipes = []
    extra_pipes = []

    for ((s, edge_coord), orig_pipe_behav) in orig_pipes
        key = (s, edge_coord)
        if haskey(gen_pipes, key)
            gen_pipe_behav = gen_pipes[key]
            pipe_match, pipe_msg = compare_pipe_behaviors(orig_pipe_behav, gen_pipe_behav; tolerance=tolerance)
            if !pipe_match
                push!(pipe_mismatches, (s, edge_coord, pipe_msg, typeof(orig_pipe_behav), typeof(gen_pipe_behav)))
            end
        else
            push!(missing_pipes, (s, edge_coord, orig_pipe_behav))
        end
    end

    for ((s, edge_coord), gen_pipe_behav) in gen_pipes
        if !haskey(orig_pipes, (s, edge_coord))
            push!(extra_pipes, (s, edge_coord, gen_pipe_behav))
        end
    end

    results["pipe_mismatches"] = pipe_mismatches
    results["missing_pipes"] = missing_pipes
    results["extra_pipes"] = extra_pipes

    # Compare ship tiles
    orig_surfaces = flatten_surfaces(original_map)
    gen_surfaces = flatten_surfaces(generated_map)
    results["surface_count_match"] = length(orig_surfaces) == length(gen_surfaces)
    results["original_surface_count"] = length(orig_surfaces)
    results["generated_surface_count"] = length(gen_surfaces)

    missing_surface = setdiff(orig_surfaces, gen_surfaces)
    extra_surface = setdiff(gen_surfaces, orig_surfaces)

    results["missing_surface"] = collect(missing_surface)
    results["extra_surface"] = collect(extra_surface)

    # Compare circuit elements (with tolerance for floating point precision)
    element_results = compare_elements(original_map, generated_map; tolerance=tolerance)
    results["elements_match"] = element_results.elements_match
    results["original_element_count"] = element_results.original_element_count
    results["generated_element_count"] = element_results.generated_element_count
    results["missing_elements"] = element_results.missing_elements
    results["extra_elements"] = element_results.extra_elements

    # Check for shared component references (critical bug check)
    orig_identity_valid, orig_identity_msg = check_component_identity(original_map)
    gen_identity_valid, gen_identity_msg = check_component_identity(generated_map)

    results["identity_check_passed"] = gen_identity_valid || (!gen_identity_valid && !orig_identity_valid)
    results["identity_check_message"] = gen_identity_msg
    results["original_has_shared_refs"] = !orig_identity_valid

    # Overall match status
    results["perfect_match"] = (results["component_count_match"] &&
                               results["pipe_count_match"] &&
                               results["surface_count_match"] &&
                               results["elements_match"] &&
                               results["identity_check_passed"] &&
                               isempty(tile_mismatches) &&
                               isempty(missing_in_generated) &&
                               isempty(extra_in_generated) &&
                               isempty(pipe_mismatches) &&
                               isempty(missing_pipes) &&
                               isempty(extra_pipes) &&
                               isempty(missing_surface) &&
                               isempty(extra_surface))

    return results
end

"""
    print_comparison_results(results::Dict)

Print formatted comparison results to stdout.
"""
function print_comparison_results(results::Dict)
    println("=" ^ 60)
    println("MAP COMPARISON RESULTS")
    println("=" ^ 60)
    
    if results["perfect_match"]
        println("✅ PERFECT MATCH: Generated map exactly matches original!")
        return
    end
    
    println("📊 SUMMARY:")
    println("  Ships: $(length(results["original_ships"])) original, $(length(results["generated_ships"])) generated - $(results["ship_names_match"] ? "✅" : "❌")")
    println("  Tiles (components): $(results["original_component_count"]) original, $(results["generated_component_count"]) generated - $(results["component_count_match"] ? "✅" : "❌")")
    println("  Pipes: $(results["original_pipe_count"]) original, $(results["generated_pipe_count"]) generated - $(results["pipe_count_match"] ? "✅" : "❌")")
    println("  Ship Surface: $(results["original_surface_count"]) original, $(results["generated_surface_count"]) generated - $(results["surface_count_match"] ? "✅" : "❌")")
    println("  Circuit Elements: $(results["original_element_count"]) original, $(results["generated_element_count"]) generated - $(results["elements_match"] ? "✅" : "❌")")
    println("  Component Identity: $(results["identity_check_passed"] ? "✅ No problematic shared references" : "❌ Shared references detected")")
    
    # Print identity check errors first (most critical) - but only if it's a real problem
    if !results["identity_check_passed"]
        println("\n❌ SHARED COMPONENT REFERENCES DETECTED:")
        println("Components with mutable state must not be reused across multiple tiles!")
        println(results["identity_check_message"])
        println("\nFix: Create separate instances for each placement or use deepcopy().")
    elseif !isempty(results["identity_check_message"]) && get(results, "original_has_shared_refs", false)
        println("\nℹ️  Note: Shared references detected but also present in original map (likely harmless immutable structs)")
    end
    
    if !isempty(results["missing_elements"]) || !isempty(results["extra_elements"])
        println("\n❌ CIRCUIT ELEMENT MISMATCHES:")
        if !isempty(results["missing_elements"])
            println("  Missing elements (present in original but not in generated):")
            # Print up to first 10 missing elements with details
            for (i, (elem, count)) in enumerate(results["missing_elements"])
                if i > 10
                    println("    ... and $(length(results["missing_elements"]) - 10) more missing elements")
                    break
                end
                println("    [$count×] $(elem.type) connecting $(elem.connections.v1) ↔ $(elem.connections.v2), value=$(elem.value)")
            end
        end
        if !isempty(results["extra_elements"])
            println("  Extra elements (present in generated but not in original):")
            # Print up to first 10 extra elements with details
            for (i, (elem, count)) in enumerate(results["extra_elements"])
                if i > 10
                    println("    ... and $(length(results["extra_elements"]) - 10) more extra elements")
                    break
                end
                println("    [$count×] $(elem.type) connecting $(elem.connections.v1) ↔ $(elem.connections.v2), value=$(elem.value)")
            end
        end
    end
    
    if !isempty(results["tile_mismatches"])
        println("\n❌ TILE MISMATCHES:")
        for (coord, issue, orig, gen) in results["tile_mismatches"]
            println("  $coord: $issue")
            println("    Original: $orig")
            println("    Generated: $gen")
        end
    end
    
    if !isempty(results["missing_tiles"])
        println("\n❌ MISSING TILES IN GENERATED MAP:")
        for coord in results["missing_tiles"]
            println("  $coord")
        end
    end
    
    if !isempty(results["extra_tiles"])
        println("\n⚠️  EXTRA TILES IN GENERATED MAP:")
        for coord in results["extra_tiles"]
            println("  $coord")
        end
    end
    
    if !isempty(results["pipe_mismatches"])
        println("\n❌ PIPE BEHAVIOR MISMATCHES:")
        for (edge_coord, msg, orig_type, gen_type) in results["pipe_mismatches"]
            println("  $edge_coord: $msg")
            println("    Original: $orig_type")
            println("    Generated: $gen_type")
        end
    end
    
    if !isempty(results["missing_pipes"])
        println("\n❌ MISSING PIPES IN GENERATED MAP:")
        for (edge_coord, pipe_behav) in results["missing_pipes"]
            println("  $edge_coord: $(typeof(pipe_behav))")
        end
    end
    
    if !isempty(results["extra_pipes"])
        println("\n⚠️  EXTRA PIPES IN GENERATED MAP:")
        for (edge_coord, pipe_behav) in results["extra_pipes"]
            println("  $edge_coord: $(typeof(pipe_behav))")
        end
    end
    
    if !isempty(results["missing_surface"])
        println("\n❌ MISSING SHIP SURFACE TILES:")
        for coord in results["missing_surface"]
            println("  $coord")
        end
    end
    
    if !isempty(results["extra_surface"])
        println("\n⚠️  EXTRA SHIP SURFACE TILES:")
        for coord in results["extra_surface"]
            println("  $coord")
        end
    end
end

"""
    compare_map_files(original_map_input::String, generator_file::String)

Main comparison function that loads original map and executes generated code.

# Arguments
- `original_map_input`: Path to map file (.jld2) or map name (for maps/ folder)
- `generator_file`: Path to the .jl file containing the mapgen function
"""
function compare_map_files(original_map_input::String, generator_file::String)
    # Load original map
    println("Loading original map: $original_map_input")
    original_map = loadmap(original_map_input)
    
    # Extract map name from path for function lookup
    # Strip .jld2 extension and get basename
    map_basename = basename(original_map_input)
    original_mapname = replace(map_basename, ".jld2" => "")

    # Load and execute generator function
    println("Loading generator function from: $generator_file")
    if !isfile(generator_file)
        error("Generator file not found: $generator_file")
    end

    # Include the generator file to define the function
    include(abspath(generator_file))

    # Try to call the expected function name exactly as derived from the map basename
    function_name = Symbol("mapgen_" * replace(original_mapname, ".jld2" => ""))
    if !isdefined(Main, function_name)
        error("Function $function_name not found in $generator_file. Expected function name: $(function_name) in $generator_file")
    end
    found_fn = getfield(Main, function_name)
    found_name = string(function_name)

    println("Executing generator function: $found_name")
    generated_map = Base.invokelatest(found_fn)
    
    # Compare the maps
    results = compare_maps(original_map, generated_map)
    
    # Print results
    print_comparison_results(results)
    
    return results
end

# CLI Interface
function main()
    if length(ARGS) < 2
        println(stderr, "Error: Both original map path and generator file required")
        println(stderr, "Usage: julia --project=. tools/map_encoder/compare_maps.jl <original_map_path> <generator_function_file>")
        exit(1)
    end
    
    original_map_input = ARGS[1]
    generator_file = ARGS[2]
    
    try
        results = compare_map_files(original_map_input, generator_file)
        exit(results["perfect_match"] ? 0 : 1)  # Exit with error code if not perfect match
    catch e
        println(stderr, "Error: $e")
        exit(1)
    end
end

