# Helper function to resolve a .jld2 map path
function resolve_map_path(input::String)
    endswith(input, ".jld2") || error("Map input must be a path to a .jld2 file: $input")
    isfile(input) || error("Map file not found: $input")
    return input
end

"Load a map through the app's canonical save-loading path."
function load_game_map(map_input::Union{Nothing, String})
    return isnothing(map_input) ? loadmap(nothing) : loadmap(resolve_map_path(map_input))
end

"""
    encode_map(map_input::String, output_file::Union{String,Nothing}=nothing)

Encode a GameMap from JLD2 format into human-readable text format.

# Arguments
- `map_input`: Path to a map file (.jld2)
- `output_file`: Optional output file path. If nothing, prints to stdout only.

# Returns
- `String`: The encoded map content
"""
# Note: We do not perform aggressive sanitization here - the agent invoking
# this tool should supply a suitable basename. We will use the file basename (sans
# extension) directly for function naming so it's transparent and editable by the user.
function get_basename(input::String)
    base = basename(input)
    base = replace(base, ".jld2" => "")
    return base
end

#= ---------- Coordinate Formatting ----------- =#

"Format a TileCoord as a readable constructor call."
format_coord(tc::TileCoord) = "TileCoord($(Int(tc.q)), $(Int(tc.r)))"

"Format a VertexCoord as a readable constructor call."
format_coord(vc::VertexCoord) = "VertexCoord($(format_coord(vc.tile)), HexFrame.$(vc.dir))"

"Format an EdgeCoord as a readable constructor call."
format_coord(ec::EdgeCoord) = "EdgeCoord($(format_coord(ec.v1)), $(format_coord(ec.v2)))"

"Sanitise a ship name symbol into a valid Julia variable suffix."
function ship_var_name(ship_name::Symbol)
    raw = string(ship_name)
    suffix = lowercase(replace(raw, r"[^A-Za-z0-9]" => "_"))
    suffix = replace(suffix, r"_+" => "_")
    suffix = strip(suffix, '_')
    return "ship_" * (isempty(suffix) ? "unnamed" : suffix)
end

function generate_mapgen_code(gamemap::GameMap, funcname::String; mapnote="")
    lines = String[]
    push!(lines, "# Generated map creation function")
    push!(lines, "# Auto-generated by tools/map_encoder/encode_map.jl")
    push!(lines, "# Note: Space map and learning system are not encoded (see map_encode_instructions.md)")
    if !isempty(mapnote)
        push!(lines, "# $mapnote")
    end
    push!(lines, "function $funcname()")

    ship_entries = collect(gamemap.ships)

    # Single-ship shortcut: use GameMap(ship) convenience constructor
    if length(ship_entries) == 1 && first(ship_entries).first == :primary
        ship = first(ship_entries).second
        push!(lines, "    ship = ShipMap()")
        emit_ship_contents!(lines, "ship", ship)
        push!(lines, "    return GameMap(ship)")
    else
        # Multi-ship: construct each ShipMap and combine
        push!(lines, "    # Construct ShipMaps individually and combine into a GameMap")
        for (ship_name, ship) in ship_entries
            var = ship_var_name(ship_name)
            push!(lines, "")
            push!(lines, "    # Ship :$(ship_name)")
            push!(lines, "    $var = ShipMap()")
            emit_ship_contents!(lines, var, ship)
        end

        push!(lines, "")
        push!(lines, "    map = GameMap()")
        for (ship_name, _) in ship_entries
            var = ship_var_name(ship_name)
            raw = string(ship_name)
            push!(lines, "    map.ships[Symbol($(repr(raw)))] = $var")
        end
        push!(lines, "    return map")
    end

    push!(lines, "end")
    return join(lines, "\n")
end

"Emit component, pipe, and surface lines for a single ShipMap."
function emit_ship_contents!(lines::Vector{String}, var::String, ship::ShipMap)
    # Components
    if !isempty(ship.components)
        push!(lines, "    components = Dict{TileCoord, ComponentOnTile}()")
        for (coord, cot) in ship.components
            push!(lines, "    components[$(format_coord(coord))] = ComponentOnTile($(repr(cot.component)), HexFrame.$(cot.rotation))")
        end
        push!(lines, "    set_component!($var, components)")
    end

    # Pipes
    if !isempty(ship.pipe_behaviors)
        push!(lines, "    pipes = Dict{EdgeCoord, PipeBehavior}()")
        for (ec, pb) in ship.pipe_behaviors
            push!(lines, "    pipes[$(format_coord(ec))] = $(repr(pb))")
        end
        push!(lines, "    set_pipe!($var, pipes)")
    end

    # Ship surface — assign directly to replace ShipMap's default {TileCoord(0,0)}
    if !isempty(ship.ship_tiles)
        push!(lines, "    $var.ship_tiles = Set{TileCoord}([")
        for coord in ship.ship_tiles
            push!(lines, "        $(format_coord(coord)),")
        end
        push!(lines, "    ])")
    end
end

function encode_map(map_input::String, output_file::Union{String,Nothing}=nothing)
    # Load the map
    gamemap = load_game_map(map_input)
    
    # Create formatted output (human-readable summary)
    lines = String[]
    push!(lines, "GameMap(")

    for (ship_name, ship) in gamemap.ships
        push!(lines, "  Ship( :$(ship_name) )")
        # Format components dictionary for this ship
        push!(lines, "    components = Dict{TileCoord, ComponentOnTile}([")
        for (coord, comp_on_tile) in ship.components
            comp_str = repr(comp_on_tile)
            push!(lines, "      $(format_coord(coord)) => $comp_str,")
        end
        push!(lines, "    ]),")

        # Format pipe_behaviors dictionary for this ship
        push!(lines, "    pipe_behaviors = Dict{EdgeCoord, PipeBehavior}([")
        for (edge_coord, pipe_behavior) in ship.pipe_behaviors
            pipe_str = repr(pipe_behavior)
            push!(lines, "      $(format_coord(edge_coord)) => $pipe_str,")
        end
        push!(lines, "    ]),")

        # Format ship_tiles set for this ship
        push!(lines, "    ship_tiles = Set{TileCoord}([")
        for coord in ship.ship_tiles
            push!(lines, "      $(format_coord(coord)),")
        end
        push!(lines, "    ])")
        push!(lines, "")
    end

    push!(lines, ")")
    
    # Join all lines
    output_content = join(lines, "\n")
    
    # Print to stdout
    println(output_content)
    
    # Optionally write to file
    if !isnothing(output_file)
        # If user asked for a .jl output, emit a mapgen function instead
        if endswith(lowercase(output_file), ".jl")
            base = get_basename(map_input)
            funcname = "mapgen_" * base
            mapnote = "Generated from $map_input"
            code = generate_mapgen_code(gamemap, funcname; mapnote=mapnote)
            # If user gave a bare filename like "mapgen_xxx.jl", default to src/demo_maps
            dir = dirname(output_file)
            if dir == "." || isempty(dir)
                dir = joinpath("src", "demo_maps")
            else
                mkpath(dir)
            end
            mkpath(dir)
            outpath = abspath(joinpath(dir, basename(output_file)))
            open(outpath, "w") do io
                write(io, code)
            end
            @info "Mapgen function written to: $outpath (function: $funcname)"
        else
            open(output_file, "w") do io
                write(io, output_content)
            end
            @info "Map encoded and written to: $output_file"
        end
    end
    
    return output_content
end

# CLI Interface
function main()
    if length(ARGS) == 0
        println(stderr, "Error: Map path required")
        println(stderr, "Usage: julia --project=. tools/map_encoder/encode_map.jl <map_path> [output_file]")
        exit(1)
    end
    
    map_input = ARGS[1]
    output_file = length(ARGS) >= 2 ? ARGS[2] : nothing
    
    try
        encode_map(map_input, output_file)
    catch e
        println(stderr, "Error: $e")
        exit(1)
    end
end

# Run main if script is executed directly
if abspath(PROGRAM_FILE) == @__FILE__
    main()
end